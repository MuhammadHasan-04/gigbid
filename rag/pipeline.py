"""Configurable retrieval pipeline. Each variant in rag/variants is a RetrievalConfig preset, so
one command (`make eval-rag`) reruns every variant and every ablation.

Retrieval unit = project (all evidence about one project: case study, README, code, CV line,
reviews), falling back to the evidence item when no project is known.
"""
from __future__ import annotations

from dataclasses import dataclass, field, replace

import numpy as np

from agent import llm
from rag.index.embed import Embedder, default_embedder
from rag.index.stores import BM25Index, Chunk, DenseIndex, rrf, tokenize
from rag.ingest.loaders import Evidence, load_persona
from rag.skills import GENERIC, tag_skills


@dataclass(frozen=True)
class RetrievalConfig:
    name: str = "v0"
    chunking: str = "fixed"         # fixed | structural
    chunk_chars: int = 500
    query: str = "whole"            # whole | decompose | hyde | decompose+hyde
    retrieval: str = "dense"        # dense | bm25 | hybrid
    rerank: str = "none"            # none | bge | llm
    outcome_boost: float = 0.0      # V4
    multi_vector: bool = False      # V5
    contextual: bool = False        # V6
    corrective: bool = False        # V8
    candidates: int = 40


@dataclass
class Hit:
    unit: str
    score: float
    chunks: list[Chunk] = field(default_factory=list)
    requirement: str | None = None

    @property
    def title(self) -> str:
        return self.chunks[0].meta.get("title", self.unit) if self.chunks else self.unit

    def evidence_ids(self) -> list[str]:
        return list(dict.fromkeys(c.evidence_id for c in self.chunks))


# ------------------------------------------------------------------ chunking
def _fixed_chunks(ev: Evidence, size: int) -> list[str]:
    t = ev.text
    step = int(size * 0.9)
    return [t[i:i + size] for i in range(0, max(1, len(t)), step)] or [t]


def _view(ev: Evidence) -> str:
    return {"case_study": "summary", "cv": "summary", "review": "summary", "readme": "readme", "code": "code",
            "upload": "summary"}.get(ev.type, "summary")


def context_line(ev: Evidence) -> str:
    """V6: a context line prepended to every chunk. With an LLM profile this is generated by the
    `contextualize` prompt once per item at index time; offline it is built from metadata."""
    skills = ", ".join(ev.skills[:6])
    return (f"[{ev.type.replace('_', ' ')} for project '{ev.title}' ({ev.industry or 'n/a'}, {ev.date or 'n/a'})"
            f"{'; skills: ' + skills if skills else ''}]")


def build_chunks(items: list[Evidence], cfg: RetrievalConfig) -> list[Chunk]:
    chunks = []
    for ev in items:
        if ev.type == "proposal":
            continue  # past proposals are a separate index (V4), never claimed as evidence
        meta = {"persona": ev.persona, "type": ev.type, "project_id": ev.project_id, "title": ev.title,
                "skills": ev.skills, "date": ev.date, "industry": ev.industry, "source": ev.source}
        if cfg.chunking == "fixed":
            pieces = _fixed_chunks(ev, cfg.chunk_chars)
        else:  # structural: sections for markdown, whole item otherwise
            pieces = [s for s in ev.text.split("\n## ") if s.strip()] if ev.type in ("case_study", "readme") else [ev.text]
        for i, p in enumerate(pieces):
            c = Chunk(f"{ev.evidence_id}#{i}", ev.evidence_id, p, dict(meta, skills=tag_skills(p, code=ev.type == "code") or ev.skills),
                      view=_view(ev))
            if cfg.contextual:
                c.context = context_line(ev)
            chunks.append(c)
    return chunks


# ------------------------------------------------------------------ query side
def job_text(job: dict) -> str:
    return f"{job.get('title', '')}\n{job.get('description', '')}"


def hyde_doc(job: dict, requirements: list[str]) -> str:
    def heuristic() -> str:
        return (f"I recently delivered {job.get('title', 'a similar project')} for a {job.get('industry', '')} client. "
                f"I built it with {', '.join(requirements)} and documented the results.")
    return llm.text("writer", "hyde", heuristic, max_tokens=220,
                    job=llm.untrusted("job_post", job_text(job)), requirements=", ".join(requirements))


# ------------------------------------------------------------------ retriever
class Retriever:
    def __init__(self, persona: str, cfg: RetrievalConfig, items: list[Evidence] | None = None,
                 embedder: Embedder | None = None):
        self.persona, self.cfg = persona, cfg
        self.items = items if items is not None else load_persona(persona)
        self.embedder = embedder or default_embedder()
        self.chunks = build_chunks(self.items, cfg)
        self.dense = DenseIndex(self.chunks, self.embedder) if cfg.retrieval in ("dense", "hybrid") else None
        self.bm25 = BM25Index(self.chunks) if cfg.retrieval in ("bm25", "hybrid") else None
        self.proposals = [e for e in self.items if e.type == "proposal"]
        self._pmat = self.embedder.embed([p.text + " " + p.title for p in self.proposals]) if (cfg.outcome_boost and self.proposals) else None
        self._reranker = None

    # -------- single query -> chunk scores
    def _search(self, query: str) -> dict[int, float]:
        n = self.cfg.candidates
        if self.cfg.retrieval == "dense":
            return {i: s for i, s in self.dense.search(query, n)}
        if self.cfg.retrieval == "bm25":
            return {i: s for i, s in self.bm25.search(query, n)}
        d = [i for i, _ in self.dense.search(query, n)]
        b = [i for i, _ in self.bm25.search(query, n)]
        return rrf([d, b])

    def _units(self, scores: dict[int, float]) -> list[Hit]:
        groups: dict[str, Hit] = {}
        for i, s in sorted(scores.items(), key=lambda x: -x[1]):
            c = self.chunks[i]
            h = groups.setdefault(c.unit, Hit(c.unit, 0.0))
            if not h.chunks:
                h.score = s
            h.chunks.append(c)
        if self.cfg.multi_vector:
            # V5: summary, README and code are separate vectors; every distinct view that matched
            # adds a vote, so a repo whose README looks irrelevant can still win through its code.
            for h in groups.values():
                views = {x.view for x in h.chunks}
                h.score = h.score * (1 + 0.15 * (len(views) - 1))
        return sorted(groups.values(), key=lambda h: -h.score)

    def _rerank(self, query: str, hits: list[Hit]) -> list[Hit]:
        if self.cfg.rerank == "none" or not hits:
            return hits
        top = hits[:20]
        if self.cfg.rerank == "bge":
            if self._reranker is None:
                from sentence_transformers import CrossEncoder  # needs HF weights
                self._reranker = CrossEncoder("BAAI/bge-reranker-v2-m3")
            scores = self._reranker.predict([(query, h.chunks[0].index_text[:1500]) for h in top])
        else:
            from rag.rerank_llm import llm_scores
            scores = llm_scores(query, [h.chunks[0].index_text[:800] for h in top])
        for h, s in zip(top, scores):
            h.score = float(s)
        return sorted(top, key=lambda h: -h.score) + hits[20:]

    def _boost_outcomes(self, query: str, hits: list[Hit]) -> list[Hit]:
        """V4: projects cited in similar past proposals that won or got replies move up."""
        if not self.cfg.outcome_boost or self._pmat is None:
            return hits
        q = self.embedder.embed([query])[0]
        sims = self._pmat @ q
        weight = {"won": 1.0, "replied": 0.6, "ignored": -0.4}
        boost: dict[str, float] = {}
        for idx in np.argsort(-sims)[:15]:
            p = self.proposals[idx]
            if p.project_id:
                boost[p.project_id] = boost.get(p.project_id, 0.0) + weight.get(p.outcome or "", 0) * float(sims[idx])
        if not hits:
            return hits
        scale = max(abs(h.score) for h in hits) or 1.0
        for h in hits:
            h.score += self.cfg.outcome_boost * scale * boost.get(h.unit, 0.0)
        return sorted(hits, key=lambda h: -h.score)

    def retrieve_query(self, query: str, k: int = 10) -> list[Hit]:
        hits = self._units(self._search(query))
        hits = self._rerank(query, hits)
        hits = self._boost_outcomes(query, hits)
        return hits[:k]

    def retrieve(self, job: dict, requirements: list[str] | None = None, k: int = 10) -> list[Hit]:
        reqs = requirements or []
        jt = job_text(job)
        if self.cfg.corrective:
            from rag.variants.v8_corrective import corrective_retrieve
            return corrective_retrieve(self, job, reqs, k)
        if self.cfg.query == "whole" or not reqs:
            q = jt if "hyde" not in self.cfg.query else hyde_doc(job, reqs)
            return self.retrieve_query(q, k)
        queries = []
        if "decompose" in self.cfg.query:
            specific = [r for r in reqs if r not in GENERIC] or reqs
            queries += [f"{r} — {job.get('title', '')}" for r in specific]
        if "hyde" in self.cfg.query:
            queries.append(hyde_doc(job, reqs))
        # merge per-requirement rankings with RRF; remember which requirement found each unit
        rankings, first_req = [], {}
        per = {}
        for q in queries:
            hs = self.retrieve_query(q, k=max(k, 10))
            rankings.append([h.unit for h in hs])
            for h in hs:
                per.setdefault(h.unit, h)
                first_req.setdefault(h.unit, q.split(" — ")[0])
        fused = rrf(rankings)
        out = []
        for unit, s in sorted(fused.items(), key=lambda x: -x[1])[:k]:
            h = per[unit]
            out.append(Hit(unit, s, h.chunks, first_req.get(unit)))
        return out

    def evidence_for(self, requirement: str, k: int = 3) -> list[Hit]:
        return self.retrieve_query(requirement, k)


def with_overrides(cfg: RetrievalConfig, **kw) -> RetrievalConfig:
    return replace(cfg, **kw)
